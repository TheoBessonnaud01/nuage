export type LineContext = keyof typeof lines;

const lastIndex = new Map<LineContext, number>();

/** Tire une réplique au hasard, jamais la même deux fois de suite pour un contexte donné. */
export function pickLine(context: LineContext, firstName: string, random: () => number = Math.random): string {
  const list = lines[context];
  const prev = lastIndex.get(context);
  let i = Math.floor(random() * list.length);
  if (list.length > 1 && i === prev) i = (i + 1) % list.length;
  lastIndex.set(context, i);
  return list[i].replaceAll('{prenom}', firstName);
}
